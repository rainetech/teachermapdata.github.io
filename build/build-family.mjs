#!/usr/bin/env node
// Builds the Family Plan from its parts, and checks they are in step.
//
//   node build/build-family.mjs           write family.html, family/SLOTS.md, and
//                                         refresh the generated block in index.html
//   node build/build-family.mjs --check   change nothing; fail if any of them is stale
//
// family/core.js and family/qr.js are the single source for the rules and the QR
// encoder. They are copied between the markers in index.html (where the link is
// made) and into family.html (where it is read), so the two cannot drift.
// family/config.json holds the two values a deployment may change: the latest
// term the page knows (older links get a gentle note) and the path to the page.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";
import crypto from "node:crypto";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = (file) => fs.readFileSync(path.join(root, file), "utf8");
const require = createRequire(import.meta.url);
const check = process.argv.includes("--check");
const config = JSON.parse(read("family/config.json"));

const strip = (text) => text.replace(/\nif \(typeof module !== "undefined" && module\.exports\) module\.exports = \w+;\n?/, "\n").trimEnd();

// 1. the page
const scripts = ["family/core.js", "family/strings.js", "family/activities.js", "family/render.js"].map((file) => strip(read(file))).join("\n\n")
  .replace("@FAMILY_LATEST_TERM@", config.latestTerm);
const template = read("family/page.html").replace("/*@SCRIPTS*/", () => scripts);
// The page's own policy names its one script and one stylesheet by hash, so
// nothing injected could run, and allows no network at all. (Inline style
// attributes, for the number line, are the only inline allowance, and a style
// cannot run code.)
const hash = (text) => "'sha256-" + crypto.createHash("sha256").update(text, "utf8").digest("base64") + "'";
const scriptText = /<script>([\s\S]*?)<\/script>/.exec(template)[1];
const styleText = /<style>([\s\S]*?)<\/style>/.exec(template)[1];
const policy = ["default-src 'none'", "script-src " + hash(scriptText), "style-src " + hash(styleText), "style-src-attr 'unsafe-inline'", "img-src data:", "base-uri 'none'", "form-action 'none'"].join("; ");
const page = template.replace("@CSP@", policy);

// The portal: a static page of tiles with no script at all, so its policy lets
// no script run and names only its one stylesheet.
const portalTemplate = read("family/portal.html");
const portalStyle = /<style>([\s\S]*?)<\/style>/.exec(portalTemplate)[1];
const portalPolicy = ["default-src 'none'", "script-src 'none'", "style-src " + hash(portalStyle), "img-src data:", "base-uri 'none'", "form-action 'none'"].join("; ");
const portal = portalTemplate.replace("@CSP@", portalPolicy);

// The headers a host must send: the same policy plus what a meta tag cannot say
// (no framing), and no referrer, no sharing of windows or resources, no
// sniffing, no features, no indexing, https only. A static host with no
// functions, no environment variables and no cookies. Two routes: the portal
// (/) and the MAP page (/nwea).
const common = [
  ["Strict-Transport-Security", "max-age=63072000; includeSubDomains"],
  ["X-Content-Type-Options", "nosniff"],
  ["X-Frame-Options", "DENY"],
  ["Referrer-Policy", "no-referrer"],
  ["Cross-Origin-Opener-Policy", "same-origin"],
  ["Cross-Origin-Resource-Policy", "same-origin"],
  ["Permissions-Policy", "accelerometer=(), camera=(), geolocation=(), gyroscope=(), microphone=(), payment=(), usb=(), interest-cohort=()"],
  ["X-Robots-Tag", "noindex, nofollow"],
  ["Cache-Control", "public, max-age=300"]
];
const rule = (source, csp) => ({ source, headers: [["Content-Security-Policy", csp + "; frame-ancestors 'none'"], ...common].map(([key, value]) => ({ key, value })) });
const hosting = JSON.stringify({
  "$schema": "https://openapi.vercel.sh/vercel.json",
  "cleanUrls": true,
  "trailingSlash": false,
  "framework": null,
  "buildCommand": null,
  "headers": [rule("/", portalPolicy), rule("/nwea", policy)]
}, null, 2) + "\n";

// 2. the block in the dashboard
const BEGIN = "    // <family-core> generated by build/build-family.mjs from family/core.js and family/qr.js. Do not edit here.";
const END = "    // </family-core>";
const indent = (text) => text.split("\n").map((line) => (line ? "    " + line : line)).join("\n");
const block = BEGIN + "\n    // The page a family link points to, relative to this page. A deployment can change it here.\n" +
  "    const FAMILY_PAGE_PATH = " + JSON.stringify(config.pagePath) + ";\n" +
  indent(strip(read("family/core.js"))) + "\n" + indent(strip(read("family/qr.js"))) + "\n" + END;
let index = read("index.html");
const from = index.indexOf(BEGIN);
const to = index.indexOf(END);
if (from < 0 || to < 0) { console.error("index.html has no family-core markers"); process.exit(1); }
const nextIndex = index.slice(0, from) + block + index.slice(to + END.length);

// 3. the list of slots
const core = require(path.join(root, "family/core.js"));
const activities = require(path.join(root, "family/activities.js"));
const slots = core.allSlots();
const bandOrder = core.BAND_ORDER;
const lines = ["# Activity slots", "",
  "Generated by `node build/build-family.mjs`. Do not edit by hand: fill a slot in `family/activities.js`.", ""];
const have = slots.filter((slot) => activities[slot.key]).length;
lines.push("**" + have + " of " + slots.length + " slots have content.** Each needs 2 or 3 activities, a worked example and a practice sheet, in English and Arabic.", "");
Object.keys(core.SUBJECTS).forEach((subject) => {
  lines.push("## " + core.SUBJECTS[subject].en, "", "| Band | Goal area | NWEA name (2025) | Key | Status |", "| --- | --- | --- | --- | --- |");
  bandOrder.forEach((band) => slots.filter((slot) => slot.subject === subject && slot.band === band).forEach((slot) => {
    const area = slot.code === "bal" ? { en: "Balanced profile (no area stands out)", nwea: "" } : core.AREAS[subject].find((entry) => entry.code === slot.code);
    const set = activities[slot.key];
    const status = !set ? "needs content" : (set.reviewed && set.reviewed.en && set.reviewed.ar ? "ready, reviewed" : "drafted, awaiting review");
    lines.push("| " + core.BANDS[band].en + " | " + area.en + " | " + (area.nwea || "") + " | `" + slot.key + "` | " + status + " |");
  }));
  lines.push("");
});
const report = lines.join("\n");

// family.html is the page on its own (for the open dashboard's own host); family/site/
// is what a family portal publishes: the portal at /, the same page at /nwea.
const targets = [["family.html", page], ["index.html", nextIndex], ["family/SLOTS.md", report],
  ["family/site/index.html", portal], ["family/site/nwea.html", page], ["family/site/vercel.json", hosting], ["family/site/robots.txt", "User-agent: *\nDisallow: /\n"]];
let stale = 0;
targets.forEach(([file, content]) => {
  const current = fs.existsSync(path.join(root, file)) ? read(file) : "";
  if (current === content) return;
  stale += 1;
  if (check) console.log("stale: " + file);
  else { fs.mkdirSync(path.dirname(path.join(root, file)), { recursive: true }); fs.writeFileSync(path.join(root, file), content); console.log("wrote " + file); }
});
if (check && stale) { console.error("Run: node build/build-family.mjs"); process.exit(1); }
if (!stale) console.log("family files are up to date (" + have + " of " + slots.length + " slots have content)");
